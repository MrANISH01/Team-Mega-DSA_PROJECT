#!/usr/bin/env python3
"""
Maze with Keys and Doors - Main Solver Program.
Compliant with Problem 1 Input and Output format requirements.

Usage:
    python3 maze_solver.py                      # Interactive mode
    python3 maze_solver.py -T 3 --csv maze.csv  # File mode
    python3 maze_solver.py -T 2 --random 15     # Random generator mode
    python3 maze_solver.py -T 3 --csv maze.csv --gui # Launch GUI
"""

import sys
import os
import json
import argparse
import webbrowser
from core_solver import (
    Maze, solve_bfs, load_from_csv, generate_marked_csv,
    generate_solvable_maze, export_original_csv
)

def export_maze_for_web(maze, path):
    script_dir = os.path.dirname(os.path.abspath(__file__))
    js_path = os.path.join(script_dir, "current_maze.js")
    js_content = f"""// Auto-generated by maze_solver.py for web visualizer
window.INITIAL_MAZE = {{
    "T": {maze.T},
    "grid": {json.dumps(maze.grid)},
    "path": {json.dumps(path)}
}};
"""
    with open(js_path, "w", encoding="utf-8") as f:
        f.write(js_content)

def print_grid_preview(grid, title="Grid Preview"):
    print(f"\n--- {title} ({len(grid)}x{len(grid[0])}) ---")
    for row in grid:
        print(" ".join(f"{c:>4}" for c in row))
    print("-" * 40)

def main():
    parser = argparse.ArgumentParser(description="Maze with Keys and Doors Solver")
    parser.add_argument("-T", "--types", type=int, choices=range(1, 7),
                        help="Number of distinct key/door types (1 <= T <= 6)")
    parser.add_argument("--csv", type=str, help="Option 1: Read NxN grid from CSV file path")
    parser.add_argument("--random", type=int, nargs="?", const=15, default=None,
                        help="Option 2: Generate random NxN valid maze with dimension N (default 15)")
    parser.add_argument("--out", type=str, default="shortest_path_marked.csv",
                        help="Output 2 CSV destination path (default: shortest_path_marked.csv)")
    parser.add_argument("--gui", action="store_true", help="Launch Tkinter desktop GUI visualizer")
    parser.add_argument("--web", action="store_true", help="Open web interactive visualizer")
    parser.add_argument("--quiet", action="store_true", help="Print only Output 1 integer (for automated grading)")
    
    args = parser.parse_args()

    # Determine if running in interactive mode
    is_interactive = (args.types is None and args.csv is None and args.random is None)

    if is_interactive:
        print("=" * 60)
        print("           MAZE WITH KEYS AND DOORS - SOLVER")
        print("=" * 60)
        
        # Standard input line: T (number of distinct key/door types, 1 <= T <= 6)
        while True:
            try:
                t_input = input("Enter T (number of distinct key/door types, 1 <= T <= 6): ").strip()
                T = int(t_input)
                if 1 <= T <= 6:
                    break
                print("Error: T must be an integer between 1 and 6.")
            except (ValueError, EOFError):
                print("Invalid input. Please enter an integer from 1 to 6.")

        # Options Prompt
        print("\nChoose Grid Input Option:")
        print("  1. Read NxN grid from a CSV file")
        print("  2. Generate NxN grid randomly (guaranteed solvable path)")
        while True:
            opt = input("Select option (1 or 2): ").strip()
            if opt in ('1', '2'):
                break
            print("Please enter 1 or 2.")

        if opt == '1':
            while True:
                csv_path = input("Enter CSV file path: ").strip()
                if os.path.exists(csv_path):
                    try:
                        maze = load_from_csv(csv_path, T=T)
                        break
                    except Exception as e:
                        print(f"Error reading CSV: {e}")
                else:
                    print(f"File not found: {csv_path}. Please re-enter.")
        else:
            n_input = input("Enter grid size N (e.g. 19, press Enter for default 19): ").strip()
            N = int(n_input) if n_input.isdigit() else 19
            print(f"Generating valid solvable {N}x{N} maze containing {T} keys and doors...")
            maze = generate_solvable_maze(N=N, T=T)
            saved_gen_csv = "generated_maze.csv"
            export_original_csv(maze, saved_gen_csv)
            print(f"Randomly generated maze saved to '{saved_gen_csv}'.")

        out_csv_path = args.out if args.out != "shortest_path_marked.csv" else "shortest_path_marked.csv"

    else:
        # Non-interactive / CLI mode
        T = args.types if args.types is not None else 3
        out_csv_path = args.out

        if args.csv:
            if not os.path.exists(args.csv):
                print(f"Error: CSV file not found: {args.csv}", file=sys.stderr)
                sys.exit(1)
            maze = load_from_csv(args.csv, T=T)
        elif args.random is not None:
            N = args.random
            maze = generate_solvable_maze(N=N, T=T)
            export_original_csv(maze, "generated_maze.csv")
        else:
            print("Error: Specify either --csv <path> or --random [N].", file=sys.stderr)
            sys.exit(1)

    # Solve the maze
    length, path, history = solve_bfs(maze)

    # If quiet mode, output only single integer
    if args.quiet:
        print(length)
        if length >= 0:
            generate_marked_csv(maze, path, output_path=out_csv_path)
        sys.exit(0)

    # Standard Formatted Output
    print("\n" + "=" * 60)
    print(f"OUTPUT 1: Shortest Path Length = {length}")
    print("=" * 60)

    if length >= 0:
        marked_grid = generate_marked_csv(maze, path, output_path=out_csv_path)
        print(f"\nOUTPUT 2: CSV with shortest path marked with 'x's written to:")
        print(f"  --> {os.path.abspath(out_csv_path)}")
        print("  (Keys and doors along the path remain clearly identifiable as 'x(a)', 'x(A)', etc.)")
        
        print_grid_preview(marked_grid, title="Marked Grid Preview (Output 2)")

        # Summary of events
        keys_found = [h['picked_key'] for h in history if h['picked_key']]
        doors_opened = [h['opened_door'] for h in history if h['opened_door']]
        print(f"\nExecution Summary:")
        print(f"  • Steps: {length}")
        print(f"  • Keys picked up: {keys_found if keys_found else 'None'}")
        print(f"  • Doors opened: {doors_opened if doors_opened else 'None'}")
    else:
        print("Path between 'S' and 'E' is NOT possible.")
        print("OUTPUT 1: -1")

    # Handle Visualization (Interactive Web Visualizer)
    launch_web = args.web or args.gui

    if is_interactive and length >= 0:
        print("\n" + "-" * 60)
        print("Visualization Options:")
        print("  1. Interactive Web Visualizer (In default browser)")
        print("  2. Exit without visualization")
        v_choice = input("Select visualization [1 or 2] (default 1): ").strip()
        if v_choice in ('2', 'n', 'N', 'exit', 'Exit'):
            launch_web = False
        else:
            launch_web = True

    if launch_web and length >= 0:
        html_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "visualizer.html")
        if os.path.exists(html_path):
            print(f"\nOpening interactive web visualizer in browser: file://{html_path}")
            try:
                import subprocess
                if sys.platform == "darwin":
                    subprocess.run(["open", html_path], check=False)
                else:
                    webbrowser.open(f"file://{html_path}")
            except Exception:
                webbrowser.open(f"file://{html_path}")
        else:
            print(f"Web visualizer file not found at {html_path}")

if __name__ == "__main__":
    main()
